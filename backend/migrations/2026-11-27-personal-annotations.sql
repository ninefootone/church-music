-- Personal markings synced to the account (iPad 1.3 step 3). Design: claude/personal-markings-2026-11.md.
-- One row per stroke, owned by ONE user. Only that user ever reads or writes their rows.
--   PDF ink       → song_file_id + page, kind 'pdf'
--   ChordPro ink  → song_file_id, kind 'chordpro' (page NULL; strokes are attached to chart lines)
--   Lyrics ink    → song_id, kind 'chordpro' (the app's lyrics-<songId> key)
-- Deletes are soft (deleted_at) so other devices learn about them; seq goes up on every change so the app can pull
-- "everything of mine since seq N". Re-adding a deleted id (undo of an erase) clears deleted_at.
-- Run in Railway: Postgres → Data → Query. Idempotent.
BEGIN;

CREATE SEQUENCE IF NOT EXISTS personal_annotations_seq;

CREATE TABLE IF NOT EXISTS personal_annotations (
  user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  id            UUID NOT NULL,                       -- generated by the app
  song_file_id  UUID REFERENCES song_files(id) ON DELETE CASCADE,
  song_id       UUID REFERENCES songs(id) ON DELETE CASCADE,
  kind          TEXT NOT NULL CHECK (kind IN ('pdf', 'chordpro')),
  page          INTEGER CHECK (page >= 0),
  stroke        JSONB NOT NULL,
  deleted_at    TIMESTAMPTZ,
  seq           BIGINT NOT NULL DEFAULT nextval('personal_annotations_seq'),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, id),
  CONSTRAINT personal_annotations_one_target CHECK ((song_file_id IS NULL) <> (song_id IS NULL)),
  CONSTRAINT personal_annotations_lyrics_kind CHECK (song_id IS NULL OR kind = 'chordpro'),
  CONSTRAINT personal_annotations_pdf_page CHECK (kind <> 'pdf' OR page IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_personal_annotations_user_seq ON personal_annotations (user_id, seq);
CREATE INDEX IF NOT EXISTS idx_personal_annotations_file ON personal_annotations (song_file_id);
CREATE INDEX IF NOT EXISTS idx_personal_annotations_song ON personal_annotations (song_id);

COMMIT;

-- Check (run after): expect 11 columns and 4 indexes (the primary key + the three above).
SELECT
  (SELECT COUNT(*) FROM information_schema.columns WHERE table_name = 'personal_annotations') AS columns,
  (SELECT COUNT(*) FROM pg_indexes WHERE tablename = 'personal_annotations') AS indexes;
